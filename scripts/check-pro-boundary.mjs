// Build-time guard: the Free path must never reach the Pro module.
//   node scripts/check-pro-boundary.mjs [rootDir]
// Pro tree: lib/pro, components/pro, app/api/phrasing, app/repair/@pro.
// For every OTHER source file under app/, lib/, components/ (and public/*.js):
//   1. no import / export-from / dynamic import() / require() may resolve into the Pro tree
//   2. nothing may import "@anthropic-ai/sdk" or "zod" (they exist only for Pro)
//   3. the string "/api/phrasing" must not appear
// Exit code 1 (and a printed list) on any violation. Also exported for the unit test.
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const PRO_DIRS = ["lib/pro", "components/pro", "app/api/phrasing", "app/repair/@pro"];
const FREE_ROOTS = ["app", "lib", "components", "public"];
const EXTS = [".ts", ".tsx", ".js", ".mjs", ".jsx"];
const FORBIDDEN_PACKAGES = ["@anthropic-ai/sdk", "zod"];

const walk = (dir) => (existsSync(dir) ? readdirSync(dir).flatMap((f) => { const p = path.join(dir, f); return statSync(p).isDirectory() ? (f === "node_modules" || f === ".next" || f === "vendor" ? [] : walk(p)) : [p]; }) : []);
const rel = (root, p) => path.relative(root, p).split(path.sep).join("/");
const isPro = (r) => PRO_DIRS.some((d) => r === d || r.startsWith(d + "/"));

function specifiers(src) {
  const out = [];
  const code = src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");
  for (const re of [/\bimport\s+(?:[\w*{}\s,$]+\s+from\s+)?["']([^"']+)["']/g, /\bexport\s+(?:\*|\{[^}]*\})\s+from\s+["']([^"']+)["']/g, /\bimport\s*\(\s*["'`]([^"'`]+)["'`]\s*\)/g, /\brequire\s*\(\s*["']([^"']+)["']\s*\)/g]) {
    for (const m of code.matchAll(re)) out.push(m[1]);
  }
  return out;
}

function resolves(root, fromFile, spec) {
  let target;
  if (spec.startsWith("@/")) target = path.join(root, spec.slice(2));
  else if (spec.startsWith(".")) target = path.resolve(path.dirname(fromFile), spec);
  else return null;
  return rel(root, target);
}

export function checkBoundary(root = process.cwd()) {
  const problems = [];
  for (const base of FREE_ROOTS) {
    for (const file of walk(path.join(root, base))) {
      if (!EXTS.includes(path.extname(file))) continue;
      const r = rel(root, file);
      if (isPro(r) || r === "public/precache-manifest.js") continue; // the manifest is generated by the build, not source
      const src = readFileSync(file, "utf8");
      if (src.includes("/api/phrasing")) problems.push(`${r}: mentions "/api/phrasing"`);
      for (const spec of specifiers(src)) {
        const target = resolves(root, file, spec);
        if (target && isPro(target)) problems.push(`${r}: imports ${spec} (Pro module)`);
        if (!target && FORBIDDEN_PACKAGES.some((p) => spec === p || spec.startsWith(p + "/"))) problems.push(`${r}: imports ${spec} (Pro-only package)`);
      }
    }
  }
  return problems;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = process.argv[2] ? path.resolve(process.argv[2]) : process.cwd();
  const problems = checkBoundary(root);
  if (problems.length) {
    console.error("Free/Pro boundary violated:\n" + problems.map((p) => "  " + p).join("\n"));
    process.exit(1);
  }
  console.log("Free/Pro boundary OK: no Free file imports the Pro module, the SDK, zod, or mentions /api/phrasing.");
}
